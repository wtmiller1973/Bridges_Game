#!/usr/bin/env python3
"""Synthesises every sound effect in assets/audio/sfx/ from scratch.

All sounds are generated by this script (no samples), so they are
original works released under CC0. Needs numpy and ffmpeg.

    python3 halloween/tools/make_sfx.py
"""
import os
import subprocess
import tempfile
import wave

import numpy as np

SR = 22050
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'assets', 'audio', 'sfx')
rng = np.random.default_rng(42)


def t(sec):
    return np.arange(int(SR * sec)) / SR


def env(n, attack=0.005, release=0.1):
    e = np.ones(n)
    a, r = int(SR * attack), int(SR * release)
    if a:
        e[:a] = np.linspace(0, 1, a)
    if r:
        e[-r:] *= np.linspace(1, 0, r) ** 2
    return e


def sweep(f0, f1, sec, shape=1.0):
    k = np.linspace(0, 1, int(SR * sec)) ** shape
    f = f0 + (f1 - f0) * k
    return 2 * np.pi * np.cumsum(f) / SR


def lowpass(x, cutoff):
    a = np.exp(-2 * np.pi * cutoff / SR)
    y = np.zeros_like(x)
    acc = 0.0
    for i, v in enumerate(x):
        acc = (1 - a) * v + a * acc
        y[i] = acc
    return y


def bell(freq, sec, decay=4.0):
    tt = t(sec)
    x = (np.sin(2 * np.pi * freq * tt) + 0.4 * np.sin(2 * np.pi * freq * 2.01 * tt)
         + 0.2 * np.sin(2 * np.pi * freq * 3.02 * tt))
    return x * np.exp(-decay * tt) * env(len(tt), 0.003, 0.02)


def mix(length, *parts):
    out = np.zeros(int(SR * length))
    for start, sig in parts:
        s = int(SR * start)
        n = min(len(sig), len(out) - s)
        out[s:s + n] += sig[:n]
    return out


def save(name, x, gain=0.8):
    x = x / (np.max(np.abs(x)) + 1e-9) * gain
    pcm = (x * 32767).astype(np.int16)
    with tempfile.NamedTemporaryFile(suffix='.wav', delete=False) as tmp:
        with wave.open(tmp.name, 'wb') as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(SR)
            w.writeframes(pcm.tobytes())
        subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', tmp.name, '-b:a', '64k',
                        os.path.join(OUT, name + '.mp3')], check=True)
        os.unlink(tmp.name)


os.makedirs(OUT, exist_ok=True)

# pop: quick bubbly pitch drop
ph = sweep(900, 250, 0.14, 0.5)
save('pop', np.sin(ph) * env(len(ph), 0.002, 0.08))

# poof: soft noise puff + a little rising shimmer
n = rng.standard_normal(int(SR * 0.4))
puff = lowpass(n, 1800) * np.exp(-8 * t(0.4))
save('poof', mix(0.6, (0, puff), (0.05, 0.3 * np.sin(sweep(800, 2400, 0.4)) * env(int(SR * 0.4), 0.01, 0.3))))

# sparkle: twinkly random high pings
parts = [(i * 0.06, bell(rng.uniform(1600, 3200), 0.35, 9)) for i in range(9)]
save('sparkle', mix(0.95, *parts), 0.6)

# tap: soft blip
ph = sweep(700, 900, 0.07)
save('tap', np.sin(ph) * env(len(ph), 0.002, 0.05), 0.5)

# boo: wobbly friendly ghost "woo-oo"
tt = t(0.8)
f = 330 + 120 * np.sin(np.pi * tt / 0.8) + 18 * np.sin(2 * np.pi * 6 * tt)
ph = 2 * np.pi * np.cumsum(f) / SR
save('boo', (np.sin(ph) + 0.25 * np.sin(2 * ph)) * env(len(tt), 0.08, 0.3), 0.55)

# meow: harmonic voice with a "mi-ow" pitch + brightness contour
tt = t(0.62)
k = tt / 0.62
f = 520 + 330 * np.sin(np.pi * np.minimum(k * 1.3, 1)) - 120 * k
ph = 2 * np.pi * np.cumsum(f) / SR
bright = 0.3 + 0.7 * np.sin(np.pi * k) ** 0.7
x = sum((bright ** (h - 1)) * np.sin(h * ph) / h for h in range(1, 9))
save('meow', x * env(len(tt), 0.04, 0.22), 0.7)

# woof: two short barks (pitch drop + growly noise, low-passed)


def bark(sec=0.2):
    tt = t(sec)
    ph = sweep(420, 230, sec, 0.7)
    x = sum(np.sin(h * ph) / h for h in range(1, 7)) + 0.4 * rng.standard_normal(len(tt))
    return lowpass(x, 1400) * env(len(tt), 0.01, 0.12)


save('woof', mix(0.62, (0, bark(0.2)), (0.3, bark(0.22))), 0.85)

# whoosh: band-swept noise
n = rng.standard_normal(int(SR * 0.4))
sw = np.sin(np.pi * t(0.4) / 0.4)
save('whoosh', (lowpass(n, 2500) - lowpass(n, 500)) * sw, 0.6)

# boing: springy wobble
tt = t(0.45)
f = 220 + 160 * np.exp(-5 * tt) * np.sin(2 * np.pi * 9 * tt) + 120 * tt
save('boing', np.sin(2 * np.pi * np.cumsum(f) / SR) * env(len(tt), 0.005, 0.15), 0.6)

# glow: rising magic chime (pumpkin lights up)
notes = [523, 659, 784, 1047, 1319]
save('glow', mix(1.4, *[(i * 0.12, bell(fr, 0.9, 3)) for i, fr in enumerate(notes)]), 0.7)

# jingle: short cheerful celebration tune
mel = [(0.00, 784), (0.16, 659), (0.32, 784), (0.48, 1047), (0.80, 988), (0.96, 1047), (1.12, 1175), (1.28, 1319)]
bass = [(0.0, 262), (0.48, 349), (0.96, 392), (1.28, 523)]
save('jingle', mix(2.2, *[(s, bell(fr, 0.6, 4)) for s, fr in mel],
                   *[(s, 0.6 * bell(fr, 0.8, 3)) for s, fr in bass]), 0.75)

print('sfx written to', os.path.normpath(OUT))
